-- 0086 · LA GLOBAL SIN RECIBOS DE FACTURAPI (aprobado por Luis el 17 nov 2026)
--
-- Los recibos (E-Receipts) de Facturapi son un producto aparte: $599 al mes POR
-- ORGANIZACIÓN más $0.40 por recibo (confirmado en la cuenta el 17 nov). La API
-- que ya se paga emite la factura global como un CFDI normal a público en
-- general, así que la plataforma arma la global con sus propios pagos y manda
-- su propio comprobante. Esto agrega lo que ese camino necesita.
--
-- Aditiva. Las columnas de recibos (0076, 0084) se quitan en la 0087, DESPUÉS
-- de promover el código que ya no las lee. Ninguna tiene datos (medido el 17
-- nov: 0 recibos, 0 facturas, 0 globales).

begin;

-- El folio de cada operación: el número que lleva el comprobante del cliente y
-- el concepto de ese pago en la factura global («número de identificación»,
-- guía de llenado del CFDI global). Corto, único y sin huecos que importen.
alter table public.payments
  add column if not exists folio bigint generated by default as identity;
create unique index if not exists payments_folio_unique on public.payments (folio);

alter table public.payments
  add column if not exists comprobante_enviado_at timestamptz,
  add column if not exists devuelto_al_facturar_mxn numeric(12,2);

comment on column public.payments.folio is
  'Folio de la operación (se muestra CAM-000123). Es el mismo en el comprobante que recibe el cliente y en el concepto de este pago dentro de la factura global.';
comment on column public.payments.comprobante_enviado_at is
  'Cuándo se le mandó al cliente el comprobante de pago (correo de la plataforma con el folio y el plazo para pedir factura). NULL = no se ha mandado.';
comment on column public.payments.devuelto_al_facturar_mxn is
  'Lo devuelto que el CFDI de ingreso de este pago (factura del cliente o global) YA salió descontando, porque se facturó por lo neto. Un egreso posterior sólo ampara lo devuelto por encima de esto (D19).';

-- La global cuenta PAGOS, no recibos.
alter table public.cfdi_globales
  add column if not exists pagos int not null default 0;
comment on column public.cfdi_globales.pagos is
  'Cuántos pagos entraron en esta global (un concepto «Venta» por pago, con su folio).';

commit;
